/** The rows of a sprite, with its outline added when it is drawn bare. Throws on a malformed sprite. */
export function spriteRows(key) {
  const s = SPRITES[key];
  if (!s) throw new Error('no sprite ' + key);
  const rows = s.px.map(r => String(r));
  if (rows.length !== 16 || rows.some(r => r.length !== 16)) throw new Error(`sprite ${key} must be 16 rows of 16`);
  if (!s.outline) return rows;
  const bare = new Set(String(s.bare || ''));
  const grid = rows.map(r => r.split(''));
  const filled = (x, y) => y >= 0 && y < 16 && x >= 0 && x < 16 && rows[y][x] !== '.' && !bare.has(rows[y][x]);
  for (let y = 0; y < 16; y++) for (let x = 0; x < 16; x++) {
    if (rows[y][x] !== '.') continue;
    if (filled(x - 1, y) || filled(x + 1, y) || filled(x, y - 1) || filled(x, y + 1)) grid[y][x] = 'o';
  }
  return grid.map(r => r.join(''));
}

/** The distinct colors a sprite uses (transparency aside). */
export function spriteColours(key) {
  const pal = SPRITES[key].pal;
  return [...new Set(spriteRows(key).join('').replace(/\./g, '').split('').map(ch => pal[ch]))];
}

/** The silhouette's gray: the locked badge (3.0: a locked badge is its gray silhouette). */
export const LOCKED_FILL = 'var(--line)';

/**
 * A sprite as an inline <svg>: one rect per horizontal run of a color (crisp edges, no blur at
 * any size). `locked` paints every pixel one gray. Unknown keys render nothing.
 */
export function spriteSvg(key, { size = 64, locked = false, cls = '', title = '' } = {}) {
  if (!SPRITES[key]) return '';
  const rows = spriteRows(key);
  const pal = SPRITES[key].pal;
  const rects = [];
  for (let y = 0; y < 16; y++) {
    let x = 0;
    while (x < 16) {
      const ch = rows[y][x];
      if (ch === '.') { x++; continue; }
      let w = 1;
      while (x + w < 16 && rows[y][x + w] === ch) w++;
      rects.push(`<rect x="${x}" y="${y}" width="${w}" height="1" fill="${locked ? LOCKED_FILL : pal[ch]}"/>`);
      x += w;
    }
  }
  const label = title ? `<title>${String(title).replace(/[<&>]/g, '')}</title>` : '';
  return `<svg class="sprite${cls ? ' ' + cls : ''}" width="${size}" height="${size}" viewBox="0 0 16 16" shape-rendering="crispEdges" ${title ? 'role="img"' : 'aria-hidden="true"'}>${label}${rects.join('')}</svg>`;
}
