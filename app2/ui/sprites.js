// app2/ui/sprites.js — the achievement art (screenplay 6.7, 6.7b; 3.0 "Achievements and level titles";
// M103): one hand-drawn 16 by 16 pixel object per badge, drawn at 1x and shown at 4x (64px), four
// to six colors with two or three tones of shading and a one-pixel dark outline, lit from the top
// left, on a transparent ground: no tile, circle or glow behind it. The sprite reads the same on
// every theme, so its colors are the art's own (like an image), not theme tokens; rarity is a
// colored word under the badge, never part of the art. A locked badge is the sprite's gray
// silhouette.
//
// A sprite is data: `px` is 16 rows of 16 characters, '.' transparent and every other character a
// slot in `pal`. `outline: true` adds the dark outline around the filled pixels at load, for the
// few drawn as bare shapes (the runner, the broom); every other sprite carries its outline in the
// rows. Variants (the chapter-tinted stopwatches and keyrings) reuse a drawing with a palette
// patch, which is how an artist would recolor one sprite.
//
//   SPRITES[key]                      → { pal, px }
//   spriteRows(key), spriteColours(key)
//   spriteSvg(key, { size, locked, cls, title })  → an <svg> string (crisp, one <rect> per pixel run)

