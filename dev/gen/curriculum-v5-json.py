# Emits dev/curriculum-v5.json (the v3 shape, checked by check-curriculum-map.js --v5) from the v5.1 data + map.
import json, re, sys, os
sys.path.insert(0, os.path.dirname(__file__))
from curriculum_v51_data import CHAPTERS
from curriculum_v51_map import M, NEW_TAGS, PLACEMENT, TRACKS, UNLOCK, PACKS
v3=json.load(open('dev/curriculum-v3.json'))
tags=list(v3['tags']) if isinstance(v3['tags'],list) else list(v3['tags'].keys())
for k in NEW_TAGS:
    if k not in tags: tags.append(k)
# live catalog keys from drills.js menuOrder
import subprocess
live=json.loads(subprocess.check_output(['node','-e',"global.window=global;global.localStorage={getItem:()=>null,setItem:()=>{}};try{require('./drills.js')}catch(e){};console.log(JSON.stringify((window.HOTKEY_DRILLS||{}).menuOrder||[]))"]).decode())
live=list(dict.fromkeys(live))
keys=[d['key'] for c in CHAPTERS for d in c['drills']]
missing=[k for k in keys if k not in M]; extra=[k for k in M if k not in keys]
assert not missing and not extra, (missing, extra)
kept=[k for k in keys if k in live]; new=[k for k in keys if k not in live]
absorbed={}
for k,(st,par,ab,t,r) in M.items():
    for a in ab: absorbed[a]=k
retired=[k for k in live if k not in keys]
chapters=[]
for c in CHAPTERS:
    cid=f"c{c['n']}"
    drills=[]
    for d in c['drills']:
        st,par,ab,t,r=M[d['key']]
        drills.append({'key':d['key'],'name':d['title'],'kind':'tutorial' if 'tutorial' in d['tag'] else ('capstone' if st=='capstone' else 'drill'),
                       'status':st,'absorbs':ab,'family':None,'board':None,'engine':d.get('engine',[]),'requires':r,'teaches':t,'par':par})
    chapters.append({'id':cid,'name':c['name'],'tier':c['tier'].lower(),'unlock_level':UNLOCK.get(c['n']),
                     'capstone':[d['key'] for d in c['drills'] if M[d['key']][0]=='capstone'][0],'teaches_line':c['intro'],'drills':drills})
out={'_':'CURRICULUM V5.1 — machine-readable map (Phase A, r458). Generated by dev/gen/curriculum-v5-json.py from curriculum_v51_data.py + curriculum_v51_map.py; edit those. Checked by dev/check-curriculum-map.js --v5.',
     'version':'5.1','generated_for':'2026-09-04','status':'design — nothing built beyond navigation and modeltour',
     'chapters':chapters,
     'retired':[{'key':k,'into':absorbed.get(k),'why':'v5.1: the lesson is carried by the drill named in `into` (dev/CURRICULUM_V5.md); PBs stay as a retired row (r158), the board closes'} for k in retired],
     'tags':tags,'placement':PLACEMENT,'tracks':{k:dict(id=k,**v) for k,v in TRACKS.items()},
     'engine_packs':[{'id':p,'name':n,'items':items,'unblocks':u} for p,n,items,u in PACKS]}
json.dump(out, open('dev/curriculum-v5.json','w'), indent=1, ensure_ascii=False)
# proof: teach-before-require in catalog order
taught=set(); viol=[]
for c in chapters:
    for d in c['drills']:
        for rq in d['requires']:
            if rq not in taught: viol.append((d['key'],rq))
        taught.update(d['teaches'])
never=[t for t in {r for c in chapters for d in c['drills'] for r in d['requires']} if t not in {t for c in chapters for d in c['drills'] for t in d['teaches']}]
print('live',len(live),'kept',len(kept),'new',len(new),'retired',len(retired),'total',len(keys))
print('retired keys:',' '.join(retired))
print('unabsorbed retirements:', [k for k in retired if k not in absorbed])
print('violations',len(viol)); [print('  ',v) for v in viol[:40]]
print('never taught:', never)
